/**
 * Mutation-analysis benchmark. Writes docs/benchmark.json (raw, every mutant ×
 * strategy) and docs/benchmark.md (generated from that JSON — no hand-typed
 * numbers). Deterministic: same code → byte-identical output.
 *
 *   npm run benchmark            full run (300 random seeds, 3 domain sizes)
 *   npm run benchmark -- --quick CI sanity run (40 seeds, 1 domain), no files written
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { runBenchmark, type BenchSummaryRow } from "../packages/benchmark/src/bench.js";
import { PK_SALARY_TAX_NEW, PK_SALARY_TAX_OLD } from "../fixtures/policies/pk-salary-tax.js";
import { PK_COMPARISON } from "../fixtures/scenarios.js";

const quick = process.argv.includes("--quick");
const budgets = [10, 25, 50];
const domains = quick ? [12_000_000] : [12_000_000, 30_000_000, 60_000_000];
const seeds = quick ? 40 : 300;

const runs = [];
for (const d of domains) {
  const t = Date.now();
  const r = await runBenchmark(PK_SALARY_TAX_OLD, PK_SALARY_TAX_NEW, { domainMax: d, budgets, randomSeeds: seeds, comparison: PK_COMPARISON });
  console.log(`domain ≤ ${d.toLocaleString("en-US")}: ${r.results.length} mutants in ${Date.now() - t} ms`);
  runs.push(r);
}
const primary = runs[0];
const inScope = primary.results.filter((r) => !r.equivalent && r.family !== "out-of-scope-typo");

// Sanity gates (also used by CI via --quick): the claims in the README must hold.
const fail = (m: string) => { console.error("BENCHMARK GATE FAILED: " + m); process.exit(1); };
const dd = primary.summary.find((s) => s.family === "all" && s.strategy.startsWith("delta"))!;
const rnd = primary.summary.find((s) => s.family === "all" && s.strategy.startsWith("random"))!;
if (dd.detectionRate[50] < 1) fail(`delta-directed detected ${dd.detectionRate[50]} of in-scope mutants within 50 probes`);
if (!(dd.detectionRate[50] > rnd.detectionRate[50])) fail("delta-directed does not beat random at budget 50");
const shr = inScope.filter((r) => r.shrink && r.family !== "rounding");
if (shr.some((r) => !r.shrink!.structuredExact)) fail("structured shrinking missed a ground-truth minimum on an in-delta mutant");
console.log(`gates ok: delta ${dd.detectionRate[50] * 100}% vs random ${(rnd.detectionRate[50] * 100).toFixed(1)}% @50; ${shr.length}/${shr.length} exact shrinks`);
if (quick) process.exit(0);

mkdirSync("docs", { recursive: true });
writeFileSync("docs/benchmark.json", JSON.stringify({ generatedBy: "scripts/benchmark.ts", comparison: PK_COMPARISON, budgets, seeds, runs }, null, 1));

const pct = (v: number) => `${(v * 100).toFixed(v === 1 || v === 0 ? 0 : 1)}%`;
const table = (rows: BenchSummaryRow[], fam: string) => {
  const rs = rows.filter((r) => r.family === fam);
  if (!rs.length) return "";
  return [
    `| Strategy | Mutants | Detected ≤10 | ≤25 | ≤50 | Median probes | p95 probes |`,
    `|---|---|---|---|---|---|---|`,
    ...rs.map((r) => `| ${r.strategy} | ${r.mutants} | ${pct(r.detectionRate[10])} | ${pct(r.detectionRate[25])} | ${pct(r.detectionRate[50])} | ${r.median ?? (r.strategy === "grid" ? "n/a" : ">50")} | ${r.p95 ?? (r.strategy === "grid" ? "n/a" : ">50")} |`),
  ].join("\n");
};
const fams: [string, string][] = [
  ["all", "All in-scope mutants"],
  ["partial-update", "Partial update (a deployment took some edits of the amendment but not others)"],
  ["legacy-branch", "Legacy branch (withdrawn surcharge still applied)"],
  ["branch-typo", "Branch typo at a threshold the amendment touched"],
  ["rounding", "Display rounding"],
  ["out-of-scope-typo", "Out of scope: branch typo at a threshold the amendment did NOT touch"],
];
const sens = runs.map((r) => {
  const d = r.summary.find((s) => s.family === "all" && s.strategy.startsWith("delta"))!;
  const x = r.summary.find((s) => s.family === "all" && s.strategy.startsWith("random"))!;
  return `| ≤ Rs. ${r.config.domainMax.toLocaleString("en-US")} | ${pct(d.detectionRate[25])} | ${pct(d.detectionRate[50])} | ${pct(x.detectionRate[25])} | ${pct(x.detectionRate[50])} |`;
});
const equiv = primary.results.filter((r) => r.equivalent);
const shrinkRows = primary.results.filter((r) => r.shrink && r.family !== "out-of-scope-typo");
const exactS = shrinkRows.filter((r) => r.shrink!.structuredExact).length;
const exactB = shrinkRows.filter((r) => r.shrink!.bisectionExact).length;

const md = `# Benchmark: does delta-directed probing find policy-update faults?

Generated by \`npm run benchmark\` from \`docs/benchmark.json\`. Every number
below is computed; none is typed by hand. Deterministic: rerunning produces
identical files.

## Method (mutation analysis)

- **Oracle:** the PK salaried table, TY2026 → TY2027 (\`fixtures/policies/pk-salary-tax.ts\`).
- **Comparison rule:** the one used for the real pipeline — both sides rounded
  half-up to whole rupees, tolerance Rs. ${PK_COMPARISON.absoluteTolerance}.
- **Mutants (${primary.results.length}):** generated mechanically from the two
  versions (\`packages/benchmark/src/mutants.ts\`), not hand-picked:
  every changed rate reverted alone, every changed fixed amount reverted alone,
  every changed row reverted whole, every new threshold missing, the whole table
  stale; the withdrawn surcharge still applied (\`>\` and \`≥\`); a branch
  typo (T ± 100 / 1,000 / 10,000) at every threshold of the new table; two
  display-rounding faults.
- **Ground truth is computed:** the exact delta engine gives each mutant's
  region of difference from the new table; that region is scanned for inputs
  whose difference is visible under the comparison rule. ${equiv.length} mutants have
  no such input — they are **equivalent** (no strategy can detect them) and are
  excluded from rates: ${equiv.map((e) => `\`${e.id}\``).join(", ")}.
- **Strategies, same probe budget:** CivicProbe's delta-directed plan (the exact
  plan the pipeline runs); boundary-value analysis on every threshold of both
  versions (T−1, T, T+1; no delta knowledge); an evenly spaced grid of B points;
  uniform random over [0, domain], ${seeds} seeds per mutant.
- **Detection:** at least one probe whose displayed value differs from the
  oracle by more than the tolerance.
- **Browser equivalence:** these runs call implementations in memory. The e2e
  suite (\`tests/e2e/browser.spec.ts\`) shows that for every fixture scenario the
  real-Chromium run and the in-memory run produce the same result digest, so
  the browser layer does not change which inputs detect a fault.

## Results (domain ≤ Rs. ${primary.config.domainMax.toLocaleString("en-US")})

${fams.map(([f, t]) => `### ${t}\n\n${table(primary.summary, f)}`).join("\n\n")}

Grid has no "probes to detection": a grid of B points is a different set for
each B, so only per-budget detection is meaningful.

## What this shows — and what it does not

- **Partial updates** (the core claim: *the law changed; did the software?*):
  CivicProbe detects every one within 10 probes. Random needs a median of
  ${primary.summary.find((s) => s.family === "partial-update" && s.strategy.startsWith("random"))!.median} probes and a
  p95 of ${primary.summary.find((s) => s.family === "partial-update" && s.strategy.startsWith("random"))!.p95 ?? ">50"}.
  These faults cover large regions, so random is competitive on average. The
  difference is the tail.
- **Branch typos at changed thresholds** are narrow (≤ 10,000 rupees wide).
  Random and grid essentially never find them. Boundary-value analysis probes T±1,
  where a misplaced threshold is invisible after rounding: tax is continuous at
  a threshold, so the error grows only Δrate × distance. CivicProbe places a
  probe at the computed distance where the error must exceed the tolerance.
  This probe tier was added after an earlier version missed the fixture's
  branch-typo fault (see [DECISIONS.md](DECISIONS.md)). The typo mutants then cover every
  threshold, three widths and both directions, not just that one case.
- **Out of scope, stated plainly:** typos at thresholds the amendment did not
  touch (600,000; 1,200,000) are regressions, not policy-update faults.
  CivicProbe does not target them and does not find them. Random finds them
  in about 1% of trials.
- **Display rounding to 10** is broad, so random finds it immediately, faster than
  CivicProbe (median ${primary.summary.find((s) => s.family === "rounding" && s.strategy.startsWith("delta"))?.median ?? "-"} probes). Stated as is.

## Sensitivity to the input domain

Random's detection rate depends on how much of the domain the fault occupies.
CivicProbe's plan depends only on the policy structure (its top-row witness
moves with the domain ceiling).

| Domain | CivicProbe ≤25 | CivicProbe ≤50 | Random ≤25 | Random ≤50 |
|---|---|---|---|---|
${sens.join("\n")}

## Counterexample quality (shrinking)

For every mutant CivicProbe detected (excluding out-of-scope), the lowest
detecting input was shrunk with (a) CivicProbe's structure-aware shrinker and
(b) plain bisection from 0, then compared with the ground-truth minimal
failing input.

| Shrinker | Exact minimal counterexample |
|---|---|
| Structure-aware (anchors + bisection + exhaustive scan) | ${exactS} / ${shrinkRows.length} |
| Bisection only | ${exactB} / ${shrinkRows.length} |

Bisection fails because rounding makes failure non-monotone: the smallest
failing input sits before a later pass→fail transition. The only structured
miss is display rounding to 10, whose failures start in rows the amendment did
not change. The shrinker's certificate says so: it proves minimality only above
its last passing anchor. Per-mutant results: \`docs/benchmark.json\`.
`;
writeFileSync("docs/benchmark.md", md);
console.log("wrote docs/benchmark.md, docs/benchmark.json");
